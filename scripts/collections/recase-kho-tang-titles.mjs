//
// The casing is a hand-checked table rather than a rule: words like "Hai",
// "Ba", "Vàng" and "Nam" are names in some titles and ordinary words in others.
//
// Idempotent; re-running on already-cased data changes nothing.
//   node scripts/collections/recase-kho-tang-titles.mjs

