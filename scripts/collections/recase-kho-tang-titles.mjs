const CASED = new Map(TITLES);
const DONE = new Set(CASED.values());

const files = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });

const unknown = new Set();
let changed = 0;

const write = (path, before, after) => {
  if (after === before) return;
  writeFileSync(path, after);
  changed++;
};

// JSON: rewrite every "*title" string value in place, keeping the file's layout.
const TITLE_FIELD = /("\w*title": )("(?:[^"\\]|\\.)*")/g;

// Markdown: "# I. TITLE", "## 12. TITLE[^1]"; a footnote marker may sit mid-title.
const HEADING = /^(#+ (?:\d+\. )?)(.+)$/gm;
const FOOTNOTE = /\[\^\d+\]/g;

const recaseHeading = (line, prefix, text) => {
  const markers = [];
  const bare = text.replace(FOOTNOTE, (marker, offset) => {
    markers.push({ marker, at: offset - markers.reduce((n, m) => n + m.marker.length, 0) });
    return "";
  });
  const cased = CASED.get(bare);
  if (!cased) return line;
  let out = cased;
  for (const { marker, at } of markers.reverse()) {
    if (at !== bare.length && cased.length !== bare.length)
      throw new Error(`Cannot place ${marker} in recased heading: ${text}`);
    const i = at === bare.length ? out.length : at;
    out = out.slice(0, i) + marker + out.slice(i);
  }
  return prefix + out;
};

for (const path of files(DATA_DIR)) {
  if (path.endsWith("table_of_contents.json")) {
    const before = readFileSync(path, "utf-8");
    const after = before.replace(TITLE_FIELD, (field, key, raw) => {
      const title = JSON.parse(raw);
      if (DONE.has(title)) return field;
      const cased = CASED.get(title);
      if (!cased) {
        unknown.add(title);
        return field;
      }
      return key + JSON.stringify(cased);
    });
    write(path, before, after);
  } else if (path.endsWith(".md")) {
    const before = readFileSync(path, "utf-8");
    write(path, before, before.replace(HEADING, recaseHeading));
  }
}

if (unknown.size) {
  console.error("Titles missing from the table:\n" + [...unknown].join("\n"));
  process.exit(1);
}
console.log(`Recased titles in ${changed} files.`);
