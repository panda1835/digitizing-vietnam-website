/**
 * A stretch of text with its markup. `general` marks an Expansion (the
 * General Abbreviation it replaced), `source` a Source Abbreviation.
 */
export interface Run {
  text: string;
  em?: boolean;
  strong?: boolean;
  general?: string;
  source?: string;
}

export interface Citation {
  abbreviation: string;
  pages: string;
}

export interface Variant {
  label: string;
  text: Run[];
  citations: Citation[];
}

export interface Correction {
  wrong: string;
  sources: string[];
  right: Run[];
  sentence: Run[];
}

/** A resolved See-also has an anchor and preview; an Unresolved one has neither. */
export interface SeeAlso {
  name: string;
  anchor?: string;
  preview?: string;
}

export interface ProverbEntry {
  name: string;
  anchor: string;
  letter: string;
  number: number;
  proverb: string;
  citations: Citation[];
  variants: Variant[];
  notes: Run[][];
  corrections: Correction[];
  see_also: SeeAlso[];
  first_syllable: string;
  sources: string[];
  has_notes: boolean;
  has_variants: boolean;
  has_correction: boolean;
  earliest_year: number | null;
  book_pages: string[];
  pdf_pages: number[];
  fixed: boolean;
  /** The Entry Image's file name in the export, e.g. "B-1.png"; see entryImageUrl. */
  image: string;
}

export interface Source {
  abbreviation: string;
  title: string;
  author: string | null;
  kind: string;
  year: number | null;
  /** Shared by every volume of a multi-volume Source, e.g. NASL I–IV. */
  note_id: string;
  note: string;
}

export type Sources = Record<string, Source>;

/** A Tiểu chủ đề of the Topic Index, with its Proverb Entries' anchors in book order. */
export interface TieuChuDe {
  id: string;
  number: number;
  title: string;
  entries: string[];
  /** Anchors the Topic Index names that no exported entry has. */
  unresolved: string[];
  /** Why the list is known to be incomplete, e.g. a misprinted page. */
  note?: string;
}

/** One of the Topic Index's four Chủ đề, I–IV. */
export interface ChuDe {
  id: string;
  title: string;
  subtopics: TieuChuDe[];
}

/** The id of a Source Note's heading on the intro page. */
export function sourceNoteId(noteId: string): string {
  return `nguon-${noteId}`;
}

/** "C-484" → "C"; anchors are `<letter>-<number>`. */
export function letterOfAnchor(anchor: string): string {
  return anchor.slice(0, anchor.lastIndexOf("-"));
}

/** Lowercase, with tone marks and diacritics removed: "Đầu" → "dau". */
export function foldDiacritics(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .toLowerCase();
}

/** The Từ điển page, without the locale; a Từ điển Entry's id is its hash. */
export const TU_DIEN_PATH = "/research/ca-dao-tuc-ngu/tu-dien";

/**
 * Generated by scripts/collections/match-tu-dien.mjs, outside the Kho
 * export's folder so that folder can still be replaced wholesale.
 */
const TU_DIEN_MATCHES_URL = "/data/ca-dao-tuc-ngu-links/tu-dien-matches.json";

/** Kho's abbreviations for the two volumes of the book on the Từ điển page. */
const VC_ABBREVIATIONS = ["VC I", "VC II"];

/** A Từ điển Entry carrying the same saying as a Proverb Entry. */
export interface TuDienMatch {
  id: string;
  kind: "exact" | "approximate";
  /** The Từ điển page's letter file the entry is filed under. */
  letter: string;
}

/** The fields of a Từ điển Entry the entry modal shows. */
export interface TuDienEntry {
  id: string;
  poem: string;
  category?: string;
  explanation?: string;
}

/** Từ điển Matches by Proverb Entry anchor; unmatched anchors are absent. */
export type TuDienMatches = Record<string, TuDienMatch[]>;

/** Whether the entry, or one of its Variants, cites VC I or VC II. */
export function citesVc(entry: ProverbEntry): boolean {
  return [entry.citations, ...entry.variants.map((v) => v.citations)].some(
    (citations) =>
      citations.some((c) => VC_ABBREVIATIONS.includes(c.abbreviation))
  );
}

// Module-level caches so the list, the search and the modal share each
// fetch, and a letter is downloaded once per visit.
const letterCache: Record<string, Promise<ProverbEntry[]>> = {};
let sourcesCache: Promise<Sources> | null = null;
let topicsCache: Promise<ChuDe[]> | null = null;
let tuDienMatchesCache: Promise<TuDienMatches> | null = null;
const tuDienLetterCache: Record<string, Promise<TuDienEntry[]>> = {};

export function fetchLetter(letter: string): Promise<ProverbEntry[]> {
  if (!AVAILABLE_LETTERS.includes(letter)) return Promise.resolve([]);
  if (!letterCache[letter]) {
    letterCache[letter] = fetch(
      `${DATA_BASE}/letters/${encodeURIComponent(letter)}.json`
    )
      .then((res) => {
        if (!res.ok) throw new Error(`Letter ${letter}: HTTP ${res.status}`);
        return res.json();
      })
      .catch((e) => {
        delete letterCache[letter];
        throw e;
      });
  }
  return letterCache[letter];
}

export function fetchAllLetters(): Promise<ProverbEntry[]> {
  return Promise.all(AVAILABLE_LETTERS.map(fetchLetter)).then((lists) =>
    lists.flat()
  );
}

export function fetchSources(): Promise<Sources> {
  if (!sourcesCache) {
    sourcesCache = fetch(`${DATA_BASE}/sources.json`)
      .then((res) => {
        if (!res.ok) throw new Error(`sources.json: HTTP ${res.status}`);
        return res.json();
      })
      .catch((e) => {
        sourcesCache = null;
        throw e;
      });
  }
  return sourcesCache;
}

export function fetchTopics(): Promise<ChuDe[]> {
  if (!topicsCache) {
    topicsCache = fetch(`${DATA_BASE}/topics.json`)
      .then((res) => {
        if (!res.ok) throw new Error(`topics.json: HTTP ${res.status}`);
        return res.json();
      })
      .then((data: { topics: ChuDe[] }) => data.topics)
      .catch((e) => {
        topicsCache = null;
        throw e;
      });
  }
  return topicsCache;
}

export function fetchTuDienMatches(): Promise<TuDienMatches> {
  if (!tuDienMatchesCache) {
    tuDienMatchesCache = fetch(TU_DIEN_MATCHES_URL)
      .then((res) => {
        if (!res.ok) throw new Error(`tu-dien-matches.json: HTTP ${res.status}`);
        return res.json();
      })
      .catch((e) => {
        tuDienMatchesCache = null;
        throw e;
      });
  }
  return tuDienMatchesCache;
}

/** The Từ điển Entry a match names, or null when its letter file lacks it. */
export async function fetchTuDienEntry(
  match: TuDienMatch
): Promise<TuDienEntry | null> {
  const { letter } = match;
  if (!tuDienLetterCache[letter]) {
    tuDienLetterCache[letter] = fetch(
      `/data/ca-dao-tuc-ngu/letters/${encodeURIComponent(letter)}.json`
    )
      .then((res) => {
        if (!res.ok) throw new Error(`${letter}.json: HTTP ${res.status}`);
        return res.json();
      })
      .catch((e) => {
        delete tuDienLetterCache[letter];
        throw e;
      });
  }
  const entries = await tuDienLetterCache[letter];
  return entries.find((e) => e.id === match.id) ?? null;
}

/** The entry an anchor names, or null when it isn't exported. */
export async function findEntry(anchor: string): Promise<ProverbEntry | null> {
  const entries = await fetchLetter(letterOfAnchor(anchor));
  return entries.find((e) => e.anchor === anchor) ?? null;
}
